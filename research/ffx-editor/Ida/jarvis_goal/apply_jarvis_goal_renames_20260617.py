def parse_rows(text, has_kind=False):
    rows = []
    for raw in text.splitlines():
        raw = raw.strip()
        if not raw or raw.startswith("#"):
            continue
        parts = raw.split()
        if has_kind:
            ea_s, name, kind = parts[:3]
            rows.append((int(ea_s, 16), name, kind))
        else:
            ea_s, name = parts[:2]
            rows.append((int(ea_s, 16), name))
    return rows



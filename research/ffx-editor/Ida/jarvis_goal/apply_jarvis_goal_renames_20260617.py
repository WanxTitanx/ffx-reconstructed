def current_name(ea):
    return ida_name.get_name(ea) or idc.get_name(ea) or ""


def is_auto_name(name):
    return (
        not name
        or name.startswith(("sub_", "nullsub_", "unk_", "dword_", "off_", "byte_", "word_", "loc_"))
    )


def can_replace(ea, current):
    return is_auto_name(current) or current in KNOWN_ALIASES.get(ea, set())


def create_data_item(ea, kind):
    size = 1
    array_count = 0
    if kind == "byte":
        size = 1
    elif kind == "word":
        size = 2
    elif kind == "dword":
        size = 4
    elif kind.startswith("dword_array_"):
        size = 4
        array_count = int(kind.rsplit("_", 1)[1])

    # Several late .data/.bss symbols are discovered as tails of wider unknown
    # data blobs in a fresh headless replay.  Break the local item boundary first
    # so the name can be applied at the exact address.
    try:
        ida_bytes.del_items(
            ea,
            getattr(ida_bytes, "DELIT_EXPAND", 0),
            DATA_CLEAR_SIZES.get(ea, size * max(array_count, 1)),
        )
    except Exception:
        pass

    if kind == "byte":
        idc.create_byte(ea)
    elif kind == "word":
        idc.create_word(ea)
    elif kind == "dword":
        idc.create_dword(ea)
    elif kind.startswith("dword_array_"):
        idc.create_dword(ea)
        try:
            idc.make_array(ea, array_count)
        except Exception:
            pass
    else:
        ida_bytes.create_data(ea, ida_bytes.FF_BYTE, 1, ida_idaapi.BADADDR)


def validate_target_database():
    missing = []
    for ea, label in EXPECTED_SEGMENT_SENTINELS.items():
        if ida_segment.getseg(ea) is None:
            missing.append(f"0x{ea:X} ({label})")
    if missing:
        raise RuntimeError(
            "wrong DB, unmapped flat VA layout, or unloaded segments; refusing to write report. "
            "Missing sentinels: " + ", ".join(missing)
        )


def annotate(ea, name):
    suffix = "candidate" if name.endswith("_candidate") else "structural" if name.endswith("_structural") else "proved/navigation"
    cmt = f"[Jarvis naming goal 2026-06-17] {suffix} name from aggressive-honest FFX.exe pass."
    func = ida_funcs.get_func(ea)
    if func:
        idc.set_func_cmt(func.start_ea, cmt, 1)
    idc.set_cmt(ea, cmt, 1)


def apply_one(ea, name, kind):
    cur = current_name(ea)
    row = {"ea": f"0x{ea:X}", "kind": kind, "old": cur, "new": name}
    if cur == name:
        row["status"] = "already_named"
    elif not can_replace(ea, cur):
        row["status"] = "skipped_conflict"
    else:
        flags = ida_name.SN_NOWARN | getattr(ida_name, "SN_DELTAIL", 0)
        ok = ida_name.set_name(ea, name, flags)
        row["status"] = "renamed" if ok else "failed"
    if row["status"] in {"renamed", "already_named"}:
        annotate(ea, name)
    return row


